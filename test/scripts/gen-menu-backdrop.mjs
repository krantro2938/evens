// Generates the menu's backdrop: four tile-sized PNGs that, pushed into the
// four image containers, black out the document and draw a frame around the
// menu panel.
//
// Why images and not a container: text containers are transparent (that is why
// the menu read as text-over-text), and the SDK caps a page at four image
// containers — all four are the document. So the backdrop can't be a fifth
// layer; it replaces what the tiles are showing, and the menu's text container
// draws over it via zOrderIndex.
//
// The geometry is fixed, so this runs at author time and the result is checked
// in. Re-run after changing MENU_* in src/constants.ts:
//
//     node scripts/gen-menu-backdrop.mjs
//
// Pure zlib, no dependencies: 8-bit greyscale PNG, which is the plainest thing
// a decoder can be handed. (The document tiles are palette PNGs from sharp on
// the server; if the host ever rejects these, matching that encoding is the
// first thing to try.)

import { deflateSync } from "node:zlib";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));

// Mirrors src/constants.ts. Kept as literals so this script has no TS imports.
const TILE_W = 288;
const TILE_H = 126;
const TILES_X = 2;
const TILES_Y = 2;
const MENU_W = 360;
const MENU_LINES = 6;
const MENU_LINE_H = 32;
const CONTAINER_PAD = 10;
const MENU_H = MENU_LINES * MENU_LINE_H + 2 * CONTAINER_PAD;
const BODY_W = 576;
const PAGE_H = TILE_H * TILES_Y;
const MENU_X = Math.round((BODY_W - MENU_W) / 2);
const MENU_Y = Math.round((PAGE_H - MENU_H) / 2);

// The frame sits a little outside the text container so glyphs never touch it.
const INSET = 6;
const BORDER = 2;
const FRAME = {
    x0: MENU_X - INSET,
    y0: MENU_Y - INSET,
    x1: MENU_X + MENU_W + INSET - 1,
    y1: MENU_Y + MENU_H + INSET - 1,
};

const BLACK = 0x00;
const BRIGHT = 0xff;

/** Is this page-space pixel part of the frame's stroke? */
function onFrame(px, py) {
    const { x0, y0, x1, y1 } = FRAME;
    if (px < x0 || px > x1 || py < y0 || py > y1) return false;
    return (
        px < x0 + BORDER || px > x1 - BORDER || py < y0 + BORDER || py > y1 - BORDER
    );
}

function crc32(buf) {
    let c,
        crc = 0xffffffff;
    for (let n = 0; n < buf.length; n++) {
        c = (crc ^ buf[n]) & 0xff;
        for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
        crc = c ^ (crc >>> 8);
    }
    return (crc ^ 0xffffffff) >>> 0;
}

function chunk(type, data) {
    const len = Buffer.alloc(4);
    len.writeUInt32BE(data.length);
    const body = Buffer.concat([Buffer.from(type, "ascii"), data]);
    const crc = Buffer.alloc(4);
    crc.writeUInt32BE(crc32(body));
    return Buffer.concat([len, body, crc]);
}

/** 8-bit greyscale PNG from a width*height byte array. */
function encodePng(width, height, pixels) {
    const ihdr = Buffer.alloc(13);
    ihdr.writeUInt32BE(width, 0);
    ihdr.writeUInt32BE(height, 4);
    ihdr[8] = 8; // bit depth
    ihdr[9] = 0; // colour type: greyscale
    ihdr[10] = 0; // deflate
    ihdr[11] = 0; // adaptive filtering
    ihdr[12] = 0; // no interlace

    // Each scanline is prefixed with its filter type; 0 = None.
    const raw = Buffer.alloc((width + 1) * height);
    for (let y = 0; y < height; y++) {
        raw[y * (width + 1)] = 0;
        pixels.copy
            ? pixels.copy(raw, y * (width + 1) + 1, y * width, (y + 1) * width)
            : raw.set(pixels.subarray(y * width, (y + 1) * width), y * (width + 1) + 1);
    }

    return Buffer.concat([
        Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
        chunk("IHDR", ihdr),
        chunk("IDAT", deflateSync(raw, { level: 9 })),
        chunk("IEND", Buffer.alloc(0)),
    ]);
}

const tiles = [];
for (let ty = 0; ty < TILES_Y; ty++) {
    for (let tx = 0; tx < TILES_X; tx++) {
        const originX = tx * TILE_W;
        const originY = ty * TILE_H;
        const pixels = Buffer.alloc(TILE_W * TILE_H, BLACK);
        for (let y = 0; y < TILE_H; y++) {
            for (let x = 0; x < TILE_W; x++) {
                if (onFrame(originX + x, originY + y)) {
                    pixels[y * TILE_W + x] = BRIGHT;
                }
            }
        }
        const png = encodePng(TILE_W, TILE_H, pixels);
        tiles.push(png.toString("base64"));
    }
}

const out = join(__dirname, "..", "src", "render", "menuBackdrop.ts");
writeFileSync(
    out,
    `// GENERATED by scripts/gen-menu-backdrop.mjs — do not edit by hand.
//
// Four ${TILE_W}x${TILE_H} greyscale PNGs, row-major, matching DOC_TILE_IDS.
// Pushed into the image containers while the action menu is open: they black
// out the document (a text container is transparent, so the menu was otherwise
// text over text) and carry the menu's frame, which no container can draw
// because borderWidth is fixed when the page is built.
//
// Frame: ${FRAME.x1 - FRAME.x0 + 1}x${FRAME.y1 - FRAME.y0 + 1} at (${FRAME.x0},${FRAME.y0}), ${BORDER}px stroke.
// Re-run the generator after changing MENU_* in constants.ts.

/** base64 PNG per tile, row-major. */
export const MENU_BACKDROP_TILES: readonly string[] = [
${tiles.map((t) => `    "${t}",`).join("\n")}
];
`,
);

const bytes = tiles.reduce((a, t) => a + Math.ceil((t.length * 3) / 4), 0);
console.log(`wrote ${out}`);
console.log(`  4 tiles, ${bytes} bytes total (${(bytes / 4).toFixed(0)} avg)`);
console.log(`  frame ${FRAME.x1 - FRAME.x0 + 1}x${FRAME.y1 - FRAME.y0 + 1} at (${FRAME.x0},${FRAME.y0})`);
